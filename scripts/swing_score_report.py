"""Swing Score stability report over the real test swings.

    .venv\\Scripts\\python.exe scripts\\swing_score_report.py [--out docs/agent-work/swing-score/REPORT.md]

For every analysed swing in var/qa/test_swings: measured checks, per-check
points, total, confidence and exclusions. Then stability diagnostics:

* nudge: every measurement moved by +/-1 unit (deg or % of height), one at a time -> largest total change;
* drop: every contributing check removed, one at a time -> largest total change (missing-check fairness);
* duplicate: swings 01 and 02 are the same swing filmed in two clips;
* distribution: min / max / mean / median / sd and buckets (diagnostics only, not user labels).
"""

from __future__ import annotations

import argparse
import copy
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from swingguru.scoring import VERSION, score_swing  # noqa: E402
from swingguru.verdicts import attach_verdicts  # noqa: E402


def load(path: Path) -> dict:
    return attach_verdicts(json.loads(path.read_text(encoding="utf-8")))


def with_value(analysis: dict, check_id: str, delta: float | None) -> dict:
    """A copy with one guided checkpoint nudged by ``delta`` (or removed when None)."""

    out = copy.deepcopy(analysis)
    for phase in out["phases"]:
        for check in phase["checks"]:
            if f"{phase['phase']}.{check['kind']}" == check_id and check.get("guided"):
                if delta is None:
                    check["guided"] = False
                else:
                    check["verdict"]["mapping"]["input"] += delta
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(ROOT / "docs" / "agent-work" / "swing-score" / "REPORT.md"))
    args = parser.parse_args(argv)
    rows = []
    for path in sorted((ROOT / "var" / "qa" / "test_swings").glob("*/bundle/analysis.json")):
        analysis = load(path)
        result = score_swing(analysis)
        if not result["checks"] and not result["available"]:
            rows.append({"swing": path.parts[-3][:2], "result": result, "nudge": None, "drop": None})
            continue
        base = result["total"]
        nudge = drop = 0.0
        for c in result["checks"]:
            for delta in (-1.0, 1.0):
                moved = score_swing(with_value(analysis, c["id"], delta))["total"]
                nudge = max(nudge, abs(moved - base))
            dropped = score_swing(with_value(analysis, c["id"], None))
            if dropped["available"]:
                drop = max(drop, abs(dropped["total"] - base))
        rows.append({"swing": path.parts[-3][:2], "result": result, "nudge": round(nudge, 2), "drop": round(drop, 2)})

    scored = [r for r in rows if r["result"]["available"]]
    totals = [r["result"]["total"] for r in scored]
    lines = [f"# Swing Score report ({VERSION})", "",
             "Generated by `scripts/swing_score_report.py` over `var/qa/test_swings` (real down-the-line clips).", "",
             "| Swing | Score | Measured | Confidence | Per-check points (measurement) | Excluded | Nudge ±1 | Drop one |",
             "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        res = r["result"]
        per = ", ".join(f"{c['phase'].replace('downswing', 'mid_down')} {c['name'].lower()} {c['points']:.1f} "
                        f"({c['measurement']:.1f}{c['unit'].replace('deg', '°')}{', est.' if c['estimated'] else ''})"
                        for c in res["checks"])
        exc = "; ".join(f"{e['id']}: {e['reason']}" for e in res["excluded"]) or "-"
        score = f"**{res['total']:.1f}**" if res["available"] else "no score"
        lines.append(f"| {r['swing']} | {score} | {res['measured']}/{res['eligible']} | {res['confidence']['label'] or '-'} | "
                     f"{per or '-'} | {exc} | {r['nudge'] if r['nudge'] is not None else '-'} | "
                     f"{r['drop'] if r['drop'] is not None else '-'} |")
    if totals:
        buckets = {"<4": sum(t < 4 for t in totals), "4-5.9": sum(4 <= t < 6 for t in totals),
                   "6-7.9": sum(6 <= t < 8 for t in totals), "8+": sum(t >= 8 for t in totals)}
        lines += ["", "## Distribution (diagnostics only)", "",
                  f"* swings scored: {len(totals)} of {len(rows)}",
                  f"* min {min(totals):.1f} · max {max(totals):.1f} · mean {statistics.mean(totals):.2f} · "
                  f"median {statistics.median(totals):.2f} · sd {statistics.pstdev(totals):.2f}",
                  "* buckets: " + ", ".join(f"{k}: {v}" for k, v in buckets.items()),
                  f"* largest change from nudging one measurement by 1 unit: {max(r['nudge'] for r in scored):.2f}",
                  f"* largest change from dropping one check: {max(r['drop'] for r in scored):.2f}"]
        pair = {r["swing"]: r["result"]["total"] for r in scored}
        if "01" in pair and "02" in pair:
            lines.append(f"* duplicate swing (01 vs 02, same swing in two clips): {pair['01']:.1f} vs {pair['02']:.1f}")
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[4:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
