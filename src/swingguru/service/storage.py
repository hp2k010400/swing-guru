"""Private object storage for swing videos and analysis results.

Keys are always generated by the service - ``<user_id>/<swing_id>/<name>`` -
and validated against ``KEY_RE``; nothing a client sends becomes a path.

* :class:`SupabaseStorage` - a *private* Supabase Storage bucket. The phone
  uploads straight to a signed upload URL; results are read through
  short-lived signed download URLs. The service role key never leaves the server.
* :class:`LocalStorage` - files on disk with HMAC-signed, expiring URLs served
  by this service (development and tests only).
"""

from __future__ import annotations

import hashlib
import hmac
import re
import shutil
import time
from pathlib import Path
from typing import Protocol
from urllib.parse import quote

import httpx

from .config import Settings, local_signing_secret

KEY_RE = re.compile(r"^[A-Za-z0-9-]{8,64}/[A-Za-z0-9-]{8,64}/[a-z0-9_.-]{1,40}$")
#: A whole owner's namespace: ``<user_id>/``. Account deletion removes this prefix so objects a
#: racing worker wrote after the row sweep cannot survive.
PREFIX_RE = re.compile(r"^[A-Za-z0-9-]{8,64}/$")
#: The lifetime an upload URL actually has. Local signed URLs are ours to choose; a Supabase signed
#: upload URL's expiry is set by the platform and cannot be requested per call, so the deletion
#: cleanup horizon must use *its* lifetime, not our configured preference.
SUPABASE_SIGNED_UPLOAD_TTL_S = 2 * 3600


class StorageError(Exception):
    pass


def check_key(key: str) -> str:
    if not KEY_RE.match(key) or ".." in key:
        raise StorageError("invalid object key")
    return key


def check_prefix(prefix: str) -> str:
    if not PREFIX_RE.match(prefix) or ".." in prefix:
        raise StorageError("invalid object prefix")
    return prefix


class Storage(Protocol):
    #: How long an upload URL handed to a client may still write, used for the deletion cleanup
    #: horizon so a late upload can never outlive the final sweep.
    upload_url_lifetime_s: int
    def upload_instructions(self, key: str, content_type: str) -> dict: ...
    def size(self, key: str) -> int | None: ...
    def download_to(self, key: str, path: Path) -> None: ...
    def put_file(self, key: str, path: Path, content_type: str) -> None: ...
    def signed_url(self, key: str, ttl_s: int | None = None) -> str: ...
    def signed_urls(self, keys: list[str], ttl_s: int | None = None) -> dict[str, str]: ...
    def delete(self, keys: list[str]) -> None: ...
    def delete_prefix(self, prefix: str) -> None: ...


# ---------------------------------------------------------------- local

class LocalStorage:
    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.upload_url_lifetime_s = int(settings.upload_url_ttl_s)
        self.root = settings.data_dir / "objects"
        self.root.mkdir(parents=True, exist_ok=True)
        self.secret = local_signing_secret(settings).encode("utf-8")

    def _path(self, key: str) -> Path:
        path = (self.root / check_key(key)).resolve()
        if not path.is_relative_to(self.root.resolve()):
            raise StorageError("invalid object key")
        return path

    def sign(self, key: str, method: str, exp: int) -> str:
        return hmac.new(self.secret, f"{method}|{key}|{exp}".encode(), hashlib.sha256).hexdigest()

    def verify(self, key: str, method: str, exp: int, sig: str) -> bool:
        return exp >= time.time() and hmac.compare_digest(self.sign(key, method, exp), sig)

    def _url(self, key: str, method: str, ttl: int) -> str:
        exp = int(time.time() + ttl)
        return f"{self.settings.public_url}/v1/files/{quote(key)}?exp={exp}&sig={self.sign(key, method, exp)}"

    def upload_instructions(self, key: str, content_type: str) -> dict:
        ttl = self.settings.upload_url_ttl_s
        return {"method": "PUT", "url": self._url(check_key(key), "PUT", ttl),
                "headers": {"Content-Type": content_type}, "expires_in_s": ttl}

    def size(self, key: str) -> int | None:
        path = self._path(key)
        return path.stat().st_size if path.is_file() else None

    def download_to(self, key: str, path: Path) -> None:
        source = self._path(key)
        if not source.is_file():
            raise StorageError("object not found")
        shutil.copyfile(source, path)

    def write_stream(self, key: str, stream, length: int, limit: int) -> int:
        if length > limit:
            raise StorageError("too large")
        target = self._path(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        # Atomic: the object only exists once fully written (see the API's PUT route).
        partial = target.with_name(target.name + ".part")
        written = 0
        try:
            with partial.open("wb") as handle:
                while written < length:
                    chunk = stream.read(min(1 << 20, length - written))
                    if not chunk:
                        break
                    handle.write(chunk)
                    written += len(chunk)
            partial.replace(target)
        finally:
            partial.unlink(missing_ok=True)
        return written

    def put_file(self, key: str, path: Path, content_type: str) -> None:
        target = self._path(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)

    def open(self, key: str) -> Path:
        return self._path(key)

    def signed_url(self, key: str, ttl_s: int | None = None) -> str:
        return self._url(check_key(key), "GET", ttl_s or self.settings.signed_url_ttl_s)

    def signed_urls(self, keys: list[str], ttl_s: int | None = None) -> dict[str, str]:
        return {key: self.signed_url(key, ttl_s) for key in keys}

    def delete(self, keys: list[str]) -> None:
        for key in keys:
            path = self._path(key)
            if path.is_file():
                path.unlink()
            try:
                path.parent.rmdir()
            except OSError:
                pass

    def delete_prefix(self, prefix: str) -> None:
        """Remove every object under one owner's namespace (``<user_id>/``), or raise.

        Errors are never swallowed: account deletion must be able to report honestly that its data
        step did not finish, and an ignored ``rmtree`` failure would silently leave private video on
        disk. Containment is checked on the *resolved* path.
        """
        target = (self.root / check_prefix(prefix)).resolve()
        if not target.is_relative_to(self.root.resolve()):
            raise StorageError("invalid object prefix")
        if not target.exists():
            return
        try:
            shutil.rmtree(target)
        except OSError as error:
            raise StorageError(f"delete_prefix failed ({type(error).__name__})") from None


# ---------------------------------------------------------------- supabase

class SupabaseStorage:
    """Supabase Storage REST API with the service role key (server side only)."""

    #: Bounds so one namespace can never loop forever: a page, a batch, a depth and a page cap.
    LIST_PAGE = 100
    MAX_LIST_PAGES = 50
    MAX_DEPTH = 8
    DELETE_BATCH = 100
    DELETE_ATTEMPTS = 3

    def __init__(self, settings: Settings, client: httpx.Client | None = None) -> None:
        self.settings = settings
        self.upload_url_lifetime_s = SUPABASE_SIGNED_UPLOAD_TTL_S
        self.base = f"{settings.supabase_url}/storage/v1"
        self.bucket = settings.bucket
        self.http = client or httpx.Client(timeout=60.0, headers={
            "Authorization": f"Bearer {settings.supabase_service_key}", "apikey": settings.supabase_service_key})

    def _check(self, response: httpx.Response, what: str) -> httpx.Response:
        if response.status_code >= 400:
            raise StorageError(f"{what} failed ({response.status_code})")
        return response

    def upload_instructions(self, key: str, content_type: str) -> dict:
        response = self._check(self.http.post(f"{self.base}/object/upload/sign/{self.bucket}/{check_key(key)}"),
                               "create upload URL")
        path = response.json().get("url") or ""
        return {"method": "PUT", "url": f"{self.base}{path}", "headers": {"Content-Type": content_type},
                "expires_in_s": SUPABASE_SIGNED_UPLOAD_TTL_S}

    def size(self, key: str) -> int | None:
        """None when the object doesn't exist; its size in bytes otherwise (1 if it exists but the
        size isn't reported - the worker re-checks the real size after downloading)."""

        response = self.http.head(f"{self.base}/object/{self.bucket}/{check_key(key)}")
        if response.status_code in (400, 404):
            return None
        self._check(response, "stat")
        length = response.headers.get("content-length")
        if length and length.isdigit() and int(length) > 0:
            return int(length)
        info = self.http.get(f"{self.base}/object/info/{self.bucket}/{key}")
        if info.status_code < 400:
            data = info.json()
            size = data.get("size") or (data.get("metadata") or {}).get("size")
            if isinstance(size, int) and size > 0:
                return size
        return 1

    def download_to(self, key: str, path: Path) -> None:
        with self.http.stream("GET", f"{self.base}/object/{self.bucket}/{check_key(key)}") as response:
            self._check(response, "download")
            with path.open("wb") as handle:
                for chunk in response.iter_bytes(1 << 20):
                    handle.write(chunk)

    def put_file(self, key: str, path: Path, content_type: str) -> None:
        with path.open("rb") as handle:
            # Results never change once written, so devices may cache them for the signed URL's life.
            self._check(self.http.post(f"{self.base}/object/{self.bucket}/{check_key(key)}", content=handle,
                                       headers={"Content-Type": content_type, "x-upsert": "true",
                                                "cache-control": "max-age=3600"}), "upload")

    def signed_url(self, key: str, ttl_s: int | None = None) -> str:
        response = self._check(self.http.post(f"{self.base}/object/sign/{self.bucket}/{check_key(key)}",
                                              json={"expiresIn": ttl_s or self.settings.signed_url_ttl_s}), "sign")
        return f"{self.base}{response.json()['signedURL']}"

    def signed_urls(self, keys: list[str], ttl_s: int | None = None) -> dict[str, str]:
        """Sign several objects in one request (a Summary needs three; the Library one per swing)."""

        if not keys:
            return {}
        response = self._check(self.http.post(
            f"{self.base}/object/sign/{self.bucket}",
            json={"expiresIn": ttl_s or self.settings.signed_url_ttl_s, "paths": [check_key(k) for k in keys]}), "sign")
        signed = {item.get("path"): item.get("signedURL") for item in response.json() if not item.get("error")}
        missing = [key for key in keys if not signed.get(key)]
        if missing:
            raise StorageError(f"sign failed for {len(missing)} object(s)")
        return {key: f"{self.base}{signed[key]}" for key in keys}

    def delete(self, keys: list[str]) -> None:
        if keys:
            self._check(self.http.request("DELETE", f"{self.base}/object/{self.bucket}",
                                          json={"prefixes": [check_key(k) for k in keys]}), "delete")

    def list_names(self, prefix: str) -> list[str]:
        """Every object name under ``prefix``, recursively, through the documented list endpoint.

        Storage's list API returns one folder at a time and marks a folder with a null ``id``, so
        subfolders are walked explicitly. The delete API's ``prefixes`` field takes these *exact*
        object names - a folder path there is not a recursive delete, which is why removal must list
        first instead of trusting one call.
        """

        start = check_prefix(prefix)
        names: list[str] = []
        queue: list[tuple[str, int]] = [(start, 0)]
        pages = 0
        while queue:
            current, depth = queue.pop(0)
            if depth > self.MAX_DEPTH:
                raise StorageError("object tree is deeper than the supported limit")
            offset = 0
            while True:
                if pages >= self.MAX_LIST_PAGES:
                    raise StorageError("object listing exceeded the supported limit")
                response = self._check(self.http.post(
                    f"{self.base}/object/list/{self.bucket}",
                    json={"prefix": current, "limit": self.LIST_PAGE, "offset": offset,
                          "sortBy": {"column": "name", "order": "asc"}}), "list")
                pages += 1
                try:
                    entries = response.json()
                except ValueError:
                    raise StorageError("object listing returned a non-JSON body") from None
                if not isinstance(entries, list):
                    raise StorageError("object listing returned an unexpected shape")
                if not entries:
                    break
                for entry in entries:
                    if not isinstance(entry, dict) or not isinstance(entry.get("name"), str):
                        raise StorageError("object listing returned an unexpected entry")
                    name = entry["name"]
                    if name in ("", ".", "..") or "/" in name:
                        raise StorageError("object listing returned an unsafe name")
                    if entry.get("id") is None:      # a folder, not an object
                        queue.append((f"{current}{name}/", depth + 1))
                    else:
                        names.append(f"{current}{name}")
                if len(entries) < self.LIST_PAGE:
                    break
                offset += len(entries)
        return names

    def delete_prefix(self, prefix: str) -> None:
        """Delete every object under one owner's namespace by exact name, in bounded batches.

        A batch that keeps failing is an error the deletion workflow must see - never a silent
        "probably fine".
        """

        names = self.list_names(prefix)
        for start in range(0, len(names), self.DELETE_BATCH):
            self._delete_batch(names[start:start + self.DELETE_BATCH])

    def _delete_batch(self, batch: list[str]) -> None:
        last = "no attempt"
        for attempt in range(self.DELETE_ATTEMPTS):
            try:
                response = self.http.request("DELETE", f"{self.base}/object/{self.bucket}",
                                             json={"prefixes": batch})
            except httpx.HTTPError:
                last = "transport error"
            else:
                if response.status_code < 400:
                    return
                last = f"status {response.status_code}"
                if response.status_code < 500 and response.status_code != 429:
                    break
            if attempt + 1 < self.DELETE_ATTEMPTS:
                time.sleep(0.05 * (attempt + 1))
        raise StorageError(f"delete failed ({last})")


def make_storage(settings: Settings) -> Storage:
    return SupabaseStorage(settings) if settings.storage_mode == "supabase" else LocalStorage(settings)


